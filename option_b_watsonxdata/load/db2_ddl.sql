CREATE TABLE FIN_DEMO.BRANCH (
  BRANCH_CODE VARCHAR(10) NOT NULL PRIMARY KEY,
  BRANCH_NAME VARCHAR(100) NOT NULL
);

CREATE TABLE FIN_DEMO.CUSTOMER (
  CUSTOMER_ID INTEGER NOT NULL PRIMARY KEY,
  CUSTOMER_NAME VARCHAR(100) NOT NULL,
  SSN VARCHAR(20) NOT NULL,
  PHONE VARCHAR(20),
  EMAIL VARCHAR(100),
  GRADE VARCHAR(20) NOT NULL,
  BRANCH_CODE VARCHAR(10) NOT NULL REFERENCES FIN_DEMO.BRANCH (BRANCH_CODE),
  TOTAL_ASSETS DECIMAL(18,0) NOT NULL,
  JOINED_DATE DATE NOT NULL
);

CREATE TABLE FIN_DEMO.ACCOUNT (
  ACCOUNT_ID INTEGER NOT NULL PRIMARY KEY,
  CUSTOMER_ID INTEGER NOT NULL REFERENCES FIN_DEMO.CUSTOMER (CUSTOMER_ID),
  ACCOUNT_TYPE VARCHAR(20) NOT NULL,
  OPEN_DATE DATE NOT NULL,
  CREDIT_LOAN_YN CHAR(1) NOT NULL
);

CREATE TABLE FIN_DEMO.PRODUCT (
  PRODUCT_CODE VARCHAR(10) NOT NULL PRIMARY KEY,
  PRODUCT_NAME VARCHAR(100) NOT NULL,
  MARKET VARCHAR(20) NOT NULL,
  SECTOR VARCHAR(50) NOT NULL
);

CREATE TABLE FIN_DEMO.ORDERS (
  ORDER_ID BIGINT NOT NULL PRIMARY KEY,
  ACCOUNT_ID INTEGER NOT NULL REFERENCES FIN_DEMO.ACCOUNT (ACCOUNT_ID),
  PRODUCT_CODE VARCHAR(10) NOT NULL REFERENCES FIN_DEMO.PRODUCT (PRODUCT_CODE),
  SIDE VARCHAR(4) NOT NULL,
  ORDER_TYPE VARCHAR(10) NOT NULL,
  ORDER_TS TIMESTAMP NOT NULL,
  ORDER_QTY INTEGER NOT NULL,
  ORDER_PRICE DECIMAL(18,2)
);

CREATE TABLE FIN_DEMO.EXECUTIONS (
  EXEC_ID BIGINT NOT NULL PRIMARY KEY,
  ORDER_ID BIGINT NOT NULL REFERENCES FIN_DEMO.ORDERS (ORDER_ID),
  EXEC_TS TIMESTAMP NOT NULL,
  EXEC_QTY INTEGER NOT NULL,
  EXEC_PRICE DECIMAL(18,2) NOT NULL,
  EXEC_AMOUNT DECIMAL(18,0) NOT NULL,
  FEE DECIMAL(18,2) NOT NULL,
  REALIZED_PNL DECIMAL(18,0) NOT NULL
);

CREATE TABLE FIN_DEMO.BALANCE_DAILY (
  ACCOUNT_ID INTEGER NOT NULL REFERENCES FIN_DEMO.ACCOUNT (ACCOUNT_ID),
  BASE_DATE DATE NOT NULL,
  CASH_BALANCE DECIMAL(18,0) NOT NULL,
  EVAL_AMOUNT DECIMAL(18,0) NOT NULL,
  RECEIVABLE DECIMAL(18,0) NOT NULL,
  PRIMARY KEY (ACCOUNT_ID, BASE_DATE)
);

CREATE TABLE FIN_DEMO.DESK (
  DESK_ID INTEGER NOT NULL PRIMARY KEY,
  DESK_NAME VARCHAR(50) NOT NULL,
  LIMIT_AMOUNT DECIMAL(18,0) NOT NULL,
  TRADER_NAME VARCHAR(50) NOT NULL
);

CREATE TABLE FIN_DEMO.ST_POSITIONS (
  DESK_ID INTEGER NOT NULL REFERENCES FIN_DEMO.DESK (DESK_ID),
  PRODUCT_CODE VARCHAR(10) NOT NULL REFERENCES FIN_DEMO.PRODUCT (PRODUCT_CODE),
  BASE_DATE DATE NOT NULL,
  QTY INTEGER NOT NULL,
  EXPOSURE_AMOUNT DECIMAL(18,0) NOT NULL,
  UNREALIZED_PNL DECIMAL(18,0) NOT NULL,
  REALIZED_PNL DECIMAL(18,0) NOT NULL,
  PRIMARY KEY (DESK_ID, PRODUCT_CODE, BASE_DATE)
);

